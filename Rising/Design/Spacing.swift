import SwiftUI

// MARK: - Spacing (8pt Grid)

/// Collection of spacing constants following an 8pt grid system.
struct RisingSpacing {
    /// Extra extra small spacing (4pt).
    static let xxs: CGFloat = 4
    /// Extra small spacing (8pt).
    static let xs: CGFloat = 8
    /// Small spacing (12pt).
    static let sm: CGFloat = 12
    /// Medium spacing (16pt).
    static let md: CGFloat = 16
    /// Large spacing (24pt).
    static let lg: CGFloat = 24
    /// Extra large spacing (32pt).
    static let xl: CGFloat = 32
    /// Extra extra large spacing (48pt).
    static let xxl: CGFloat = 48
    /// Extra extra extra large spacing (64pt).
    static let xxxl: CGFloat = 64
}

// MARK: - Corner Radius

/// Collection of corner radius constants.
struct RisingRadius {
    /// Small corner radius (6pt).
    static let sm: CGFloat = 6
    /// Medium corner radius (8pt).
    static let md: CGFloat = 8
    /// Large corner radius (12pt).
    static let lg: CGFloat = 12
    /// Extra large corner radius (16pt).
    static let xl: CGFloat = 16
    /// Full circular corner radius.
    static let full: CGFloat = 9999
}
